 *       قبل حتى احتساب المحتوى — فاقم مشكلة الضغط/التصغير بشكل مضاعف.
 *
 *     ⚠️ هذه الإعدادات **لم تُختبَر بعد على الطابعة الفعلية** (لا تتوفر لي
 *     وصولاً مباشراً لطابعة المستودع) — بُنيت حصراً على حساب هندسي دقيق من
 *     فحص الملف الفعلي + الأبعاد الفيزيائية المُعلَنة (رول 80مم). التوصية:
 *     طباعة اختبارية واحدة بعد هذا التعديل، ثم إبلاغي بالنتيجة (عريض كافٍ؟
 *     ما زال يُقَص من الجانب؟ التوسيط انتهى فعلاً؟) لضبط الثابتين أعلاه
 *     برقم واحد دقيق بدل التقدير الحالي.
 *
 * 🆕 [جولة تنسيق 6] **تراجع صريح عن تثبيت عرض الأعمدة برقم تقديري (بند 11
 * أعلاه) — عرض "حر" محسوب من النص الفعلي، على أن يُعدَّل يدوياً عند الحاجة.**
 * صاحب المشروع فضّل عدم فرض رقم ثابت واحد (30/10) على كل الصيدليات: أسماء
 * المواد تتفاوت طولاً بشدة من صيدلية لأخرى، وأي رقم تقديري واحد إما يُضيّق
 * على أسماء طويلة (التفافها بسطرين رغم ارتفاع الصف الثابت) أو يترك فراغاً
 * زائداً مع أسماء قصيرة — وقرَّر صراحةً تحمُّل التعديل اليدوي من إكسل عند
 * الحاجة بدل رقم مكتوب بالكود يحاول تغطية كل الحالات.
 *
 * 13) **`WithColumnWidths` أُزيلت بالكامل من الكلاس، واستُبدلت بـ
 *     `ShouldAutoSize`.** هذا ليس تبديل واجهتين متكافئتين فحسب: `WithColumnWidths`
 *     تفرض رقماً معروفاً *قبل* إنتاج أي بيانات، بينما `ShouldAutoSize` تُفوِّض
 *     لـPhpSpreadsheet حساب أعرض نص فعلي بكل عمود — بالخط/الحجم الحقيقيين
 *     المُطبَّقين عبر `styles()` (Cambria 22pt Bold) — *بعد* امتلاء الورقة
 *     بالبيانات، فينتج عرضاً مختلفاً يُناسب كل كشف صيدلية بعينه، لا رقماً
 *     واحداً يُطبَّق قسراً على الجميع.
 *
 *     🎓 **لماذا لم يُجمَع الحلّان معاً** (عرض تقديري احتياطي + تلقائي)؟
 *     لأن Laravel Excel تتعامل معهما بأولوية صريحة وواحدة: أي عمود مذكور
 *     بـ `columnWidths()` يُستثنى تلقائياً من الحساب التلقائي (القيمة
 *     الثابتة تفوز دائماً لذلك العمود تحديداً) — فإبقاء الواجهتين معاً هنا
 *     كان سيُبطِل أثر `ShouldAutoSize` بالضبط على العمودين الوحيدين
 *     بالورقة، أي يُلغي القرار المطلوب بلا فائدة.
 *
 *     ⚠️ **تحذير هندسي صريح (لا تجميل)**: خوارزمية `ShouldAutoSize` بمكتبة
 *     PhpSpreadsheet مبنية على تقدير عرض حرفي تقريبي (مُعايَر أصلاً لحروف
 *     لاتينية بخط Calibri) لا قياس Unicode فعلي بكل محرف — دقّتها مع نص
 *     عربي (كحال هذا الملف بالكامل) أقل منها مع نص إنكليزي، فقد تحتاج أحياناً
 *     لمسة يدوية بسيطة بعد التصدير لحالة استثنائية (اسم طويل جداً مثلاً) —
 *     وهذا تحديداً ما وافق عليه صاحب المشروع صراحةً ("التعديل اليدوي عند
 *     الحاجة")، لا عيباً خفياً يُكتَشف لاحقاً.
 *
 *     🩹 إعدادات `PageSetup`/`PageMargins` (بند 12، الجولة السابقة) **لم
 *     تُمَسّ إطلاقاً** — بل ازدادت أهمية الآن: بما أن العرض الإجمالي للورقة
 *     لم يعد معروفاً مسبقاً (يتغيّر حسب محتوى كل صيدلية)، تبقى `FitToWidth=1`
 *     "شبكة الأمان" الوحيدة التي تضمن ملاءمة أي عرض ناتج — مهما كان — مع
 *     عرض الورق الفعلي (80مم) عند الطباعة.
 */
final class PreparationPharmacySheetExport implements FromArray, WithHeadings, WithTitle, ShouldAutoSize, WithStyles
{
    /** 🆕 عائلة الخط الموحَّدة لكامل الورقة — مصدر وحيد، راجع تعليق الكلاس بند 4. */
    private const FONT_FAMILY = 'Cambria';

    /** 🆕 الحجم الموحَّد لكامل الورقة (لا فرق بعد الآن بين عنوان/فاصل/بيانة) — راجع بند 6. */
    private const UNIFIED_FONT_SIZE = 22;

    /** 🆕 ارتفاع موحَّد لكل الصفوف — يكفي لخط 22 أينما ظهر بالورقة. */
    private const UNIFIED_ROW_HEIGHT = 34;

    /** 🆕 تسمية ثابتة لكتلة "بلا شركة مُسجَّلة" — بدل NULL صريح يصعب فرزه أو عرضه. */
    private const UNASSIGNED_COMPANY_LABEL = 'غير مصنَّف بشركة';

    /**
     * 🔄 [جولة تنسيق 4] أرقام صفوف بيانات المواد — بعد إلغاء صفوف الفاصل
     * (راجع بند 10 بتعليق الكلاس)، هذه القائمة أصبحت تسلسلاً متتابعاً بسيطاً
     * (2، 3، 4، ...) لأن كل صف بعد العنوان هو صف بيانة بلا استثناء. أُبقيت
     * كخاصية (بدل استبدالها برقم صف مباشر بالحلقة) حتى يبقى `styles()` يعتمد
     * على **ترتيب البيانات الفعلي** لا افتراض تطابقه مع رقم الصف الخام —
     * ضمانة تبقى مفيدة لو أُضيف صف من نوع آخر مستقبلاً.
     *
     * @var list<int>
     */
    private array $productDataRows = [];

    public function __construct(
        private readonly string $date,
        private readonly int $pharmacyId,
        private readonly string $pharmacyName,
        private readonly string $sheetTitle,
        private readonly ?string $status = null,
        private readonly ?string $availability = null,
    ) {}

    /**
     * 🔄 [جولة تنسيق 4] يبني مصفوفة الصفوف النهائية — صف واحد بالضبط لكل
     * مادة، بلا أي صف فاصل بينها. `fetchRows()` نفسها (الاستعلام والترتيب)
     * لم تُلمَس إطلاقاً: الصفوف تخرج هنا بالترتيب الذي أعادته `ORDER BY
     * company, product_name` تماماً كما كانت — فقط لم نعد **نحقن** صفاً
     * إضافياً بين كتلة وأخرى. "الشركة" (`$row->company`) تبقى تُقرَأ من
     * نتيجة الاستعلام (لازمة لضمان الترتيب) لكنها لا تُكتَب لأي خلية هنا.
     */
    public function array(): array
    {
        $rows = $this->fetchRows();

        $sheetRows = [];
        $excelRow = 2; // الصف 1 = صف العنوان (headings())؛ بيانات الورقة تبدأ من 2

        foreach ($rows as $row) {
            $sheetRows[] = [$row->product_name, (int) $row->total_qty];
            $this->productDataRows[] = $excelRow;
            $excelRow++;
        }

        return $sheetRows;
    }

    /**
     * 🆕 استعلام البيانات الخام فقط — بلا أي قرار عرضي (الفواصل تُبنى فوقها
     * بـ array()). الترتيب `company, product_name` معاً هو ما يُنتج "كتل
     * شركات، كل كتلة أبجدية داخلياً" تلقائياً — نتيجة طبيعية للترتيب
     * المتعدد الأعمدة، لا حاجة لتجميع إضافي بالذاكرة بعد الاستعلام.
     */
    private function fetchRows(): Collection
    {
        return DB::table('invoice_items')
            ->join('invoices', 'invoices.id', '=', 'invoice_items.invoice_id')
            ->join('products', 'products.id', '=', 'invoice_items.product_id')
            ->whereDate('invoices.date', $this->date)
            ->where('invoices.pharmacy_id', $this->pharmacyId)
            // نفس فلاتر PreparationExport::sheets() بالضبط — راجع تعليقها الكامل للسبب.
            ->when($this->status, fn($q) => $q->where('invoices.status', $this->status))
            ->when($this->availability === 'shortage', fn($q) => $q->where('invoice_items.shortage_qty', '>', 0))
            ->select([
                'products.name as product_name',
                // 🆕 COALESCE هنا بحت لعرض/ترتيب كتلة موحَّدة لمنتج بلا شركة —
                // دالة من عمود GROUP BY الفعلي (products.company)، فمقبولة تحت
                // ONLY_FULL_GROUP_BY (الاعتماد الوظيفي محفوظ: دالة واحدة ثابتة
                // من عمود مُجمَّع عليه بالفعل).
                DB::raw("COALESCE(products.company, '" . self::UNASSIGNED_COMPANY_LABEL . "') as company"),
                DB::raw('SUM(invoice_items.supplied_qty) as total_qty'),
            ])
            ->groupBy('products.id', 'products.name', 'products.company')
            // نفس قاعدة النسخة السابقة: صنف طُلب لكن لم يُشحَن منه شيء إطلاقاً لا يظهر هنا.
            ->having(DB::raw('SUM(invoice_items.supplied_qty)'), '>', 0)
            ->orderBy('company')
            ->orderBy('products.name')
            ->get();
    }

    /** صف العنوان هو الهوية نفسها — راجع تعليق الكلاس. */
    public function headings(): array
    {
        return [$this->pharmacyName, now()->format('Y-m-d H:i')];
    }

    public function title(): string
    {
        return $this->sheetTitle;
    }

    // 🔄 [جولة تنسيق 6] لا وجود بعد الآن لـ`columnWidths()` — أُزيلت تماماً مع
    // إزالة `WithColumnWidths` (راجع بند 13 بتعليق الكلاس). عرض العمودين
    // يُحسَب تلقائياً عبر `ShouldAutoSize` بالاعتماد على محتوى كل خلية فعلياً،
    // لا رقماً ثابتاً مكتوباً هنا.

    /**
     * 🆕 نقطة مصدر وحيدة لخصائص الخط المشتركة (العائلة + الحجم + العريض) —
     * كل أربع نقاط التنسيق بالأسفل تمرّ من هنا وتُضيف فقط ما يخصّها (اللون
     * عادةً). لو طُلب تغيير العائلة أو الحجم الموحَّد مستقبلاً، التعديل هنا
     * فقط — لا أربع مواضع متفرقة قابلة لنسيان إحداها (مبدأ DRY).
     *
     * @param array<string, mixed> $overrides خصائص إضافية/مُستبدِلة (مثل اللون)
     * @return array<string, mixed>
     */
    private function baseFontStyle(array $overrides = []): array
    {
        return array_merge([
            'name' => self::FONT_FAMILY,
            'bold' => true,
            'size' => self::UNIFIED_FONT_SIZE,
        ], $overrides);
    }

    public function styles(Worksheet $sheet): array
    {
        $lastRow = max(1, $sheet->getHighestRow());

        // صف العنوان: أزرق فاتح + خط كحلي، بنفس الخط/الحجم/العريض الموحَّد الآن.
        $sheet->getRowDimension(1)->setRowHeight(self::UNIFIED_ROW_HEIGHT);
        $sheet->getStyle('A1:B1')->applyFromArray([
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFBFE1F5']],
            'font' => $this->baseFontStyle(['color' => ['argb' => 'FF1A365D']]),
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);

        // 🆕 [جولة تنسيق 3] حدود الجدول: رمادي فاتح خفيف → أسود صريح كامل.
        // السبب ليس تفضيلاً جمالياً: النسخة المطبوعة الفعلية (التي أرسلها صاحب
        // المشروع) وصلت بلا أي خطوط فاصلة بين الصفوف إطلاقاً — حدود رمادية
        // فاتحة (FFD1D5DB) على طابعة ضعيفة الجودة أو بوضع طباعة اقتصادي
        // (Draft/توفير حبر) تُطبَع باهتة جداً لدرجة الاختفاء الفعلي. أسود صريح
        // بأدنى سماكة (THIN) يبقى عالي التباين حتى بأسوأ ظروف طباعة ممكنة —
        // هذا نفس سبب اختيار الأسود تحديداً لا تدرّجاً رمادياً أغمق فقط.
        $sheet->getStyle("A1:B{$lastRow}")->applyFromArray([
            'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['argb' => 'FF000000']]],
        ]);

        // 🆕 صفوف بيانات المواد: نفس الخط الموحَّد لعمودي الاسم والكمية معاً —
        // لا فارق وزن بينهما بعد الآن (الاسم أصبح عريضاً أيضاً، لا الكمية فقط).
        foreach ($this->productDataRows as $index => $row) {
            $sheet->getRowDimension($row)->setRowHeight(self::UNIFIED_ROW_HEIGHT);

            $sheet->getStyle("A{$row}")->applyFromArray([
                'font' => $this->baseFontStyle(),
                'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
            ]);
            $sheet->getStyle("B{$row}")->applyFromArray([
                'font' => $this->baseFontStyle(),
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
            ]);

            // 🔄 [جولة تنسيق 4] $index الآن يطابق ترتيب صف البيانات الفعلي
            // تلقائياً (لا صفوف فاصل تُزحزحه بعد الآن) — بقي الاعتماد على
            // $index بدل $row نفسه لأنه أوضح نيّةً (تناوب بحسب "ترتيب
            // المادة"، لا بحسب "رقم الصف الخام") حتى لو تطابقا رقمياً الآن.
            if ($index % 2 === 1) {
                $sheet->getStyle("A{$row}:B{$row}")->applyFromArray([
                    'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFF9FAFB']],
                ]);
            }
        }

        // 🆕 [جولة تنسيق 5] إعداد صريح لإعدادات الطباعة بدل تركها لإعدادات
        // الطابعة/الجلسة المحلية — راجع تعليق الكلاس بند 12 للسبب الكامل.
        // هذا تحديداً ما يمنع أي بقايا إعداد "ملاءمة كاملة" أو "توسيط"
        // عالقة من طباعة سابقة لنفس الطابعة من التأثير على هذا الملف.
        $pageSetup = $sheet->getPageSetup();
        $pageSetup->setOrientation(PageSetup::ORIENTATION_PORTRAIT);
        $pageSetup->setFitToPage(true);
        $pageSetup->setFitToWidth(1);   // صفحة واحدة عرضاً فقط
        $pageSetup->setFitToHeight(0);  // 0 = بلا حد لعدد الصفحات طولاً (رول متواصل)
        $pageSetup->setHorizontalCentered(false);
        $pageSetup->setVerticalCentered(false);

        // 🆕 هوامش مُصغَّرة بدل افتراضي إكسل (0.7/0.75 بوصة) — على ورق 80مم
        // (3.15 بوصة)، الهوامش الافتراضية وحدها كانت تلتهم نحو 44% من العرض
        // الكلي، مُفاقِمة مشكلة التصغير. راجع تعليق الكلاس بند 12.
        $margins = $sheet->getPageMargins();
        $margins->setTop(0.1);
        $margins->setBottom(0.1);
        $margins->setLeft(0.1);
        $margins->setRight(0.1);
        $margins->setHeader(0.0);
        $margins->setFooter(0.0);

        $sheet->setRightToLeft(true);

        return [];
    }
}
