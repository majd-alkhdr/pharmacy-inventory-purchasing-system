 *       عالق بجلسة طباعة سابقة لنفس الطابعة محلياً على جهاز المُستخدِم —
 *       هذا يُفسِّر مباشرة ظهور الجدول بمنتصف الصفحة بدل أعلاها.
 *     - هوامش الصفحة (`PageMargins`) خُفِّضت من الافتراضي (0.7/0.75 بوصة)
