<?php

declare(strict_types=1);

namespace App\Services\Inventory\Import\Contracts;

use App\Services\Inventory\Import\Exceptions\InvalidImportFileException;
use Generator;

/**
 * 🎯 عقد قراءة أي ملف جدولي (xlsx / csv) كتدفّق صفوف — لا يعرف شيئاً عن
 * معنى الأعمدة (مواد؟ صيدليات؟) ولا عن قاعدة البيانات. مسؤوليته الوحيدة:
 * "أعطني صفوف هذا الملف واحداً واحداً".
 *
 * 🎓 لماذا واجهة (Interface) وليس استدعاء Maatwebsite مباشرة؟
 * (1) مبدأ DIP: خدمات الاستيراد تعتمد على هذا العقد لا على مكتبة بعينها،
 *     فاستبدال القارئ (OpenSpout ← مكتبة أخرى) لا يلمس سطراً واحداً منها.
 * (2) قابلية الاختبار: الاختبارات تحقن قارئاً وهمياً يُعيد مصفوفات، بلا
 *     ملفات Excel حقيقية.
 * (3) الأداء: النوع المُعاد Generator يفرض القراءة المتدفقة — صف واحد في
 *     الذاكرة بكل لحظة بغض النظر عن حجم الملف. هذا هو الفرق الجوهري عن
 *     PharmacyInventoryImport الحالي الذي يُراكم كل الصفوف بمصفوفة.
 *
 * 📐 الشروط الملزمة لأي تطبيق:
 *  - يُعيد **كل** صف فعلي بالملف، بما فيه الفارغ، برقمه الحقيقي (يبدأ من 1).
 *    تخطي الفارغ قرار المستهلك لا القارئ: أرقام الصفوف تُستخدم بتقارير
 *    الأخطاء ("الصف 245")، وتخطيها بصمت يُزيحها فتصبح مضلِّلة.
 *  - خلايا الصف قائمة بفهرس يبدأ من 0؛ الخلية الفارغة null (لا نص فارغ).
 *  - لا يثق بأبعاد الورقة المُعلَنة (ملفات الـ ERP تُعلن أحياناً ضعف
 *    الصفوف الفعلية بسبب صفوف منسَّقة فارغة بالنهاية).
 */
interface TabularFileReader
{
    /**
     * @param  string  $absolutePath المسار الكامل للملف على القرص
     * @return Generator<int, array<int, string|int|float|bool|null>> المفتاح: رقم الصف الفعلي (من 1). القيمة: خلايا الصف (فهرس من 0).
     *
     * @throws InvalidImportFileException إن كان الملف تالفاً أو بصيغة غير مدعومة
     */
    public function read(string $absolutePath): Generator;
}
