<?php

declare(strict_types=1);

namespace App\Services\Inventory\Import\Support;

/**
 * 🎯 يُنتج "مفتاح مطابقة" (Match Key) لنص عربي — لمقارنة رؤوس الأعمدة وأسماء
 * الصيدليات، **لا** لتخزين الاسم. الاسم المخزَّن يبقى كما كتبه المستخدم؛
 * المفتاح يُستخدم فقط ليقول: "هل هذان الاسمان يقصدان نفس الشيء؟".
 *
 * 🎓 لماذا كلاس نقي منفصل (Pure Function)؟ المطابقة بالنص الحرفي هي أصل
 * مشكلة موثَّقة بتقريرك التعليمي (استثناء الشركات: خطأ إملائي بسيط يُبطل
 * التطابق بصمت). هنا الحالات الحقيقية من ملفاتك: "ماهر سليمان / جرمانا"
 * (كشف الـ ERP) مقابل "ماهر سليمان- جرمانا" (ملفك) — نفس الصيدلية بتنسيق
 * مختلف. منطق كهذا يجب أن يعيش بمكان واحد قابل للاختبار، لا مبعثراً
 * بـ str_replace متفرقة.
 *
 * ⚠️ حدود مقصودة: مخصَّص لأسماء قصيرة (رؤوس، صيدليات). لا تستخدمه لمطابقة
 * أسماء المواد — توحيد "ة/ه" و"-" هناك قد يدمج مادتين مختلفتين فعلاً.
 *
 * ⚖️ المقايضة: توحيد "ة"↔"ه" و"ى"↔"ي" يرفع نسبة المطابقة الصحيحة على حساب
 * احتمال ضئيل جداً لدمج اسمين مختلفين حقاً؛ لذلك النتيجة تُستهلَك دائماً
 * مع كشف الغموض (اسمان بنفس المفتاح = يُوقَف للتأكيد، لا يُختار أحدهما).
 */
final class ArabicTextNormalizer
{
    /** توحيد أشكال الحروف والأرقام. المفاتيح متعددة البايت — strtr آمن مع UTF-8 لأنه متزامن ذاتياً. */
    private const CHARACTER_MAP = [
        'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
        'ى' => 'ي',
        'ة' => 'ه',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
    ];

    public static function key(string $text): string
    {
        // نص بترميز تالف يجعل preg_* تُعيد null — نُصلحه بدل أن ننهار.
        if (!mb_check_encoding($text, 'UTF-8')) {
            $text = mb_convert_encoding($text, 'UTF-8', 'UTF-8');
        }

        // 1) محارف غير مرئية تضيفها ملفات Excel/ERP (علامات RTL/LTR، مسافة بعرض صفر، BOM).
        $text = (string) preg_replace('/[\x{00AD}\x{200B}-\x{200F}\x{202A}-\x{202E}\x{2066}-\x{2069}\x{FEFF}]/u', '', $text);

        // 2) كل أنواع المسافات (NBSP، Tab، سطر جديد) ← مسافة عادية، قبل معالجة الفواصل.
        $text = (string) preg_replace('/[\s\p{Z}]+/u', ' ', $text);

        // 3) التشكيل والتطويل (ـ) — لا يغيّران المعنى ويكسران المطابقة.
        $text = (string) preg_replace('/[\x{064B}-\x{065F}\x{0670}\x{0640}]/u', '', $text);

        // 4) توحيد الحروف والأرقام.
        $text = strtr($text, self::CHARACTER_MAP);

        // 5) كل أنواع الفواصل (- – — / \ |) بمسافاتها المحيطة ← "-" واحدة.
        $text = (string) preg_replace('/\s*[\-\x{2010}-\x{2015}\x{2212}\/\\\\|]\s*/u', '-', $text);
        $text = (string) preg_replace('/-{2,}/', '-', $text);

        // 6) تنظيف نهائي + تصغير الحروف اللاتينية.
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));

        return mb_strtolower($text, 'UTF-8');
    }
}
