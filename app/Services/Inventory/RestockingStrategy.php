<?php
// app/Services/Inventory/RestockingStrategy.php

namespace App\Services\Inventory;

use App\Enums\ShortageSource;

/**
 * 🎯 العقد المشترك بين استراتيجيات الترميم الثلاث (Sales / StandardInventory
 * / Hybrid). أي كلاس يطبّقه يصبح تلقائياً قابلاً للاستخدام من
 * RestockingStrategyResolver بلا أي تعديل على الكونترولر أو الـ Job.
 *
 * 🎓 لماذا Interface صريح بدل مجرد الاتفاق الضمني على اسم method؟ لأن
 * PHP لا يفرض توقيع موحَّد بين كلاسات غير مرتبطة إلا بعقد صريح — بدونه،
 * أي استراتيجية جديدة قد تنحرف بتوقيع مختلف قليلاً (execute() تُعيد array
 * بدل RestockingResult مثلاً) ولن يكتشف PHP الخطأ إلا وقت التشغيل. بوجود
 * الـ Interface، أي انحراف يُكتشف فوراً وقت الكتابة (IDE) أو وقت أي
 * static analysis (PHPStan/Larastan)، قبل وصول الكود للإنتاج إطلاقاً.
 */
interface RestockingStrategy
{
    /**
     * ينفّذ عملية الترميم الكاملة (فواتير + سجلات نقص) ضمن معاملة قاعدة
     * بيانات واحدة (DB::transaction) داخل التطبيق المحدَّد، ويُعيد ملخصاً
     * موحَّد الشكل بصرف النظر عن الاستراتيجية المُنفَّذة فعلياً.
     */
    public function execute(RestockingContext $context): RestockingResult;

    /**
     * المصدر الذي تُنسَب إليه أي سجلات نقص ينشئها هذا التطبيق تحديداً —
     * يُستخدَم لتوسيم عمود shortages.source عند الإدراج، ولا علاقة له
     * بوضع (Mode) العملية ككل (الذي قد يكون Hybrid ويُشغِّل استراتيجيتين
     * بمصدرين مختلفين معاً).
     *
     * 🩹 [مُعدَّل] nullable الآن — عند بناء HybridRestockingStrategy فعلياً
     * (لا نظرياً فقط) تبيَّن أنها لا تُناسب توقيعاً يُلزِمها بقيمة واحدة:
     * هي لا تكتب لجدول shortages مباشرة أبداً بنفسها (تُفوِّض ذلك بالكامل
     * لاستراتيجيتين فرعيتين، كل واحدة تسم نواقصها بمصدرها الصحيح بنفسها)،
     * فإلزامها بإرجاع Sales أو StandardInventory كان سيكون كذباً معمارياً
     * لا يعكس الواقع. null هنا يعني حرفياً "لا مصدر واحد يُمثِّل هذه
     * الاستراتيجية" — نفس اصطلاح RestockingResult::mergeWith() بالضبط.
     * هذا مثال حي بالضبط على النقطة المذكورة أعلاه: الواجهة اكتشفت فرضية
     * خاطئة بالتصميم الأول فور المحاولة الفعلية للتطبيق، لا قبلها.
     */
    public function source(): ?ShortageSource;
}
