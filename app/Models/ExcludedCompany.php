<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class ExcludedCompany extends Model
{
    protected $fillable = ['company'];

    /**
     * 🩹 [إصلاح جوهري 2026-09] كانت هذه الدالة تُخزِّن القائمة بخاصية
     * Static، بافتراض خاطئ أن عمرها "بنفس الطلب فقط". هذا الافتراض صحيح
     * فقط حين تُعالَج المهام داخل نفس عملية الطلب (قائمة انتظار sync) —
     * لكن QUEUE_CONNECTION هنا = database، أي أن المعالجة الفعلية تحدث
     * بعملية PHP منفصلة تماماً وطويلة الأمد (php artisan queue:work)، لا
     * تنتهي بانتهاء أي طلب ويب واحد. خاصية Static بهذه العملية الطويلة
     * تبقى محفوظة **عبر عشرات أو مئات المهام المتتالية**، حتى لو أضاف
     * مستخدم شركة جديدة للاستثناء بطلب ويب منفصل بالمنتصف — تلك الإضافة
     * تُنظِّف الكاش فقط بعملية الطلب هي نفسها (clearCache())، لا بعملية
     * queue:work المنفصلة تماماً التي لا تشاركها أي ذاكرة إطلاقاً. النتيجة
     * الفعلية: شركة مستثناة حديثاً تبقى تُرمَّم بصمت حتى إعادة تشغيل
     * عامل قائمة الانتظار — بالضبط العرض الذي ظهر فعلياً.
     *
     * الحل: بلا أي كاش هنا إطلاقاً. التكلفة مقبولة تماماً — كل مستهلك
     * فعلي (SalesImport، PharmacyInventoryImport، الخدمات المختلفة) يستدعي
     * هذه الدالة **مرة واحدة فقط** بمُنشئه الخاص أصلاً، ويُخزِّن النتيجة
     * بخاصية محلية طوال عمر ذلك الكائن — لا حاجة فعلية لكاش إضافي هنا،
     * والصحة أهم من تحسين أداء غير ضروري أصلاً.
     */
    public static function currentList(): array
    {
        return self::pluck('company')->all();
    }
}
