    /**
     * @param array<int, array<int, mixed>> $rows الصف الأول يُعتبَر عنوان (يُتجاهَل عند القراءة الفعلية — كل الـ Imports تبدأ من startRow()=2)
     */
    private function writeCsv(string $filename, array $rows): void
    {
        $fullPath = Storage::disk('local')->path("{$this->outputDir}/{$filename}");

        $handle = fopen($fullPath, 'w');

        // 🩹 BOM UTF-8 صريح — بدونه، فتح الملف مباشرة ببرنامج Excel (لا
        // القراءة الفعلية عبر Laravel Excel بالتطبيق، تلك تعمل بلا مشاكل
        // بأي الحالتين) قد يعرض الحروف العربية مشوَّهة على بعض إصدارات
        // Windows. لا يؤثر إطلاقاً على قراءة PhpSpreadsheet/Laravel Excel
        // للملف عند الرفع الفعلي — إضافة أمان لفتح الملف يدوياً للمراجعة فقط.
        fwrite($handle, "\xEF\xBB\xBF");

        foreach ($rows as $row) {
            fputcsv($handle, $row);
        }

        fclose($handle);
    }
